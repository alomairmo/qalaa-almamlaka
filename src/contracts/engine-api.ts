/**
 * ⚠️ عقد مجمّد — لا تعدّل دون تنسيق مع المنسّق
 *
 * قلاع المملكة — واجهة المحرك GameEngineApi.
 * كل إجراء ممكن في اللعبة كدوال موصوفة بأنواع دقيقة.
 * المرجع: الوثيقة التفصيلية v2.0 §11–§15 + design.md §11.
 *
 * القاعدة: الدوال ترجع `GameEvent[]` للأحداث المنجزة فورًا (لتغذية
 * أنظمة الأنيميشن والصوت)، أو void عندما يكون الأثر تغيير طور/وضع
 * يُقرأ من الـ store مباشرة.
 */

import type {
  ArmyComposition,
  ArmyTarget,
  CatapultTarget,
  GameEvent,
  GameSettings,
  GameState,
  Question,
  TeamAdjustment,
  TeamId,
} from './types';

export interface GameEngineApi {
  // ── دورة الموسم ─────────────────────────────

  /**
   * بدء موسم جديد من الصفر بحالة ابتدائية نظيفة.
   * يُستدعى من شاشة العنوان بعد تأكيد "موسم جديد".
   */
  newSeason(): GameEvent[];

  /**
   * استئناف الموسم المحفوظ محليًا.
   * يرجع null إن لم يوجد حفظ.
   */
  resumeSeason(): GameEvent[] | null;

  /** هل يوجد موسم محفوظ قابل للاستئناف؟ (لإظهار زر الاستئناف وشريط الحالة) */
  hasSavedSeason(): boolean;

  /**
   * تصفير اللعبة والإعادة — يدوي بالكامل من الإعدادات
   * (يُستدعى فقط بعد تأكيد hold-to-confirm).
   */
  resetGame(): GameEvent[];

  /**
   * إعلان الفائز (نهاية الأسبوع): يحسب الذهب الكلي لكل مجموعة
   * (داخل + خارج + في الطريق) ويعلن الأعلى.
   */
  declareWinner(): GameEvent[];

  // ── تسلسل الجولة — §12 ─────────────────────

  /**
   * بدء جولة المجموعة الحالية (زر "بدء الجولة").
   * ينقل الطور إلى السؤال (أو للتصرف مباشرة في نمط الأسئلة الشفهية
   * قبل الحكم حسب إعداد موضع الزر).
   */
  startTurn(): GameEvent[];

  /**
   * تأكيد إجابة سؤال اختياري (MCQ) — تصحيح فوري.
   * choiceIndex: مؤشر الخيار المختار بعد الخلط (0..2).
   * عند الصواب: موارد + أنيميشن ثم طور التصرف. عند الخطأ: أنيميشن خطأ ثم نهاية الجولة.
   */
  submitAnswer(choiceIndex: number): GameEvent[];

  /**
   * حكم المعلم على إجابة شفهية (نمط الأسئلة الشفهية).
   * correct=true: موارد + طور التصرف. correct=false: نهاية الجولة.
   */
  judgeOralAnswer(correct: boolean): GameEvent[];

  /**
   * إنهاء الجولة مبكرًا (زر "إنهاء الجولة") —
   * ينقل الدور فورًا للمجموعة التالية دون انتظار العدّاد.
   */
  endTurnEarly(): GameEvent[];

  // ── أفعال التصرف الحر — §11 ────────────────

  /**
   * بناء طابق جديد (−5 حجارة افتراضيًا).
   * يفشل (يرجع []) إن لم تملك المجموعة الكلفة.
   */
  buildFloor(): GameEvent[];

  /**
   * إصلاح طابق مصاب (حجر واحد = نقطتا صحة افتراضيًا لكل حجر مصروف).
   * stonesToSpend: عدد الحجارة المراد صرفها على الإصلاح.
   */
  repairFloor(floorId: string, stonesToSpend: number): GameEvent[];

  /**
   * شراء/تجنيد جندي (−5 ذهب افتراضيًا) مع سحب رتبته
   * عشوائيًا حسب احتمالات التجنيد — يُكشف بأنيميشن.
   */
  recruitSoldier(): GameEvent[];

  // ── وضع المنجنيق — §8 ──────────────────────

  /**
   * دخول وضع المنجنيق (منظور شخص أول من سطح القلعة).
   * لا يتفعّل إلا بوجود حجر واحد على الأقل. لا يخصم الحجر هنا.
   */
  enterCatapultMode(): void;

  /** إلغاء وضع الإطلاق والعودة دون خسارة الحجر (ما لم تُطلق القذيفة) */
  cancelCatapult(): void;

  /**
   * إطلاق القذيفة: يخصم الحجر، يسحب الضرر عشوائيًا حسب نوع الهدف،
   * يطبّق الأثر ويرجع أحداث الرمية والإصابة (الكاميرا تلاحق الحجر ثم تقرير الضرر).
   * power: قوة الإطلاق 0..1 (من الضغط المطوّل أو المقبض اليدوي).
   */
  fireCatapult(target: CatapultTarget, power: number): GameEvent[];

  /**
   * آخر قوة إطلاق محفوظة للمجموعة (0–100) — تُستدعى عند فتح وضع
   * المنجنيق لضبط المقبض/الإيماء على آخر قيمة. الافتراضي 50.
   */
  getCatapultPower(teamId: TeamId): number;

  /**
   * حفظ قوة المقبض/الإيماء للمجموعة (0–100) دون إطلاق
   * (مثلًا عند تحريك المقبض ثم الإلغاء). تُحفظ مع اللعبة.
   */
  setCatapultPower(teamId: TeamId, power: number): void;

  // ── وضع الجيش — §11 ────────────────────────

  /** دخول وضع الجيش: تتوسع الكاميرا وتظهر دوائر الاستهداف الحمراء */
  enterArmyMode(): void;

  /** إلغاء وضع الجيش والعودة للوضع العادي دون خصم شيء */
  cancelArmy(): void;

  /**
   * تنفيذ الإرسال من نافذة الإرسال المدمجة:
   * - هدف قلعة: معركة فورية (أو سرقة بلا قتال إن خلت من الجنود)،
   *   ثم انطلاق قافلة العودة بالغنيمة.
   * - هدف قافلة: اعتراض ميداني فوري.
   * - هدف كومة ذهب: التقاط بلا قتال وانطلاق قافلة عودة.
   */
  dispatchArmy(target: ArmyTarget, composition: ArmyComposition): GameEvent[];

  // ── الإعدادات والمعلم — §15 ────────────────

  /** تحديث جزئي للإعدادات (أي مقبض من مقابض قسم 15) */
  updateSettings(patch: Partial<GameSettings>): GameEvent[];

  /** استبدال بنك الأسئلة كاملًا (من مربع اللصق بعد التحويل لأسئلة) */
  setQuestionBank(questions: Question[]): GameEvent[];

  /**
   * منحة المعلم أو جزاؤه على مجموعة (تبويب بيانات المجموعات).
   * delta موجب = منحة (أنيميشنات إضافة متتابعة)، سالب = جزاء
   * (أنيميشن قصف من السماء على العنصر المخصوم).
   */
  applyTeacherAdjustment(teamId: TeamId, delta: TeamAdjustment): GameEvent[];

  // ── الأوضاع العامة ─────────────────────────

  /** فتح شاشة الإعدادات (Esc) — توقف كل العدّادات فورًا */
  openSettings(): void;

  /** العودة للعب من شاشة الإعدادات */
  closeSettings(): void;

  /** دخول وضع الكاميرا الحرة من شاشة الإعدادات (اللعبة متوقفة) */
  enterFreeCamera(): void;

  /** الخروج من الكاميرا الحرة إلى شاشة الإعدادات */
  exitFreeCamera(): void;

  /**
   * بدء الجولة التعريفية: سيناريو محاكاة معزول تمامًا
   * عن الأرصدة الحقيقية، تعود اللعبة بعده لحالتها المحفوظة.
   */
  startTutorial(): void;

  /** إنهاء الجولة التعريفية والعودة للحالة السابقة */
  endTutorial(): void;

  /** تخطي أنيميشن الحدث الجاري (زر "تخطي") — يكتم صوته أيضًا */
  skipEvent(): void;

  // ── قراءة الحالة ────────────────────────────

  /** لقطة حالية من حالة اللعبة (قراءة فقط — التعديل عبر الإجراءات فقط) */
  getState(): Readonly<GameState>;
}
